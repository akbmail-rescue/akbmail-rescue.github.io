/**
 * 録画手順ガイド(要件 §5)。精度目標(§9)はこの手順に従った「準拠入力」に対して定義される。
 * 2026-08-26: iPhone の自動化の限界・末尾の強めの引き・放置の可否・動画の長さと保存領域について実態に合わせて改訂。
 */
export function RecordingGuide() {
  return (
    <div className="guide">
      <h3>まず 2〜3 通で試す</h3>
      <p>
        いきなり長く録画せず、メール 2〜3 通ぶんを録画してこのページに投入し、1 通ずつ正しく分かれるかを確認してから本番の録画に進んでください。
      </p>

      <h3>おすすめ: 連続スクロール録画</h3>
      <p>AKB48 Mail アプリでは、メール本文の一番下でさらに引っ張ると次のメールに切り替わります。これを使うと 1 通あたり数秒で録画できます。</p>
      <ol>
        <li>最初のメール(最新または最古)を開いて、画面収録を開始する</li>
        <li>ゆっくりドラッグ(指を置いたまま動かす)でスクロールする。フリック(はじく)は避ける</li>
        <li>
          一番下に着いたら<strong>少し強めに引っ張って</strong>次のメールへ進める(アプリの仕様で、軽い引きでは切り替わりません)
        </li>
        <li>
          <strong>切り替わったら 2 秒静止</strong>する(本文の読み込み待ち。読み込み中の白い画面が「1 通の区切り」の目印になるので、この静止は必須)
        </li>
        <li>以降くり返し。手が疲れたら録画を止めて分けてかまいません(複数の動画をまとめて投入できます)</li>
      </ol>

      <h3>共通のルール</h3>
      <ul>
        <li>1 本の動画は <strong>5 分以内</strong>を推奨。長いほど処理に時間がかかり、途中で止まったときの損失も大きくなります(処理時間の目安: パソコンで動画の 1〜2 倍、互換モードでは 4〜7 倍)</li>
        <li>動画の大きさに上限はありません(少しずつ読み込みます)。iPhone の画面収録は 1 分あたり 50〜100MB です</li>
        <li>画像の全画面表示は開いてもかまいませんが、画像の保存はアプリの↓ボタンをおすすめします</li>
        <li>画面の明るさ最大、ダークモード OFF、通知バナー OFF、着信は機内モード推奨</li>
        <li>強めに引いて 1〜2 通飛んでしまうことがあります。結果を見て抜けがあれば、その範囲だけ録り直してください</li>
      </ul>

      <h3>代わりの方法: 一覧からタップして録画</h3>
      <p>連続スクロールが使いにくい場合は、一覧からメールを開いて 2 秒静止 → 戻る、をくり返す方法でも処理できます(1 通あたり約 4〜5 秒)。</p>

      <h3>iPhone: 手を離して進めたいとき(AssistiveTouch)</h3>
      <p>
        iPhone には操作を自動でくり返す機能が無いため、<strong>完全な放置はできません</strong>。代わりに「録っておいた操作をボタン 1 回で再生する」ことはできます。
      </p>
      <ol>
        <li>設定 → アクセシビリティ → タッチ → AssistiveTouch をオン</li>
        <li>同じ画面の「新規ジェスチャを作成」を開く</li>
        <li>
          画面上で実際の操作を録る: ゆっくり上へドラッグ(1〜2 秒)→ 指を離して 2 秒待つ → もう一度ゆっくりドラッグ → … を続けられるだけ続け、最後に「一番下で少し強めに引く」動きも入れる(1 回の録画に何通ぶんも入れられます)
        </li>
        <li>右上の「保存」で名前を付ける(例: メール送り)</li>
        <li>AKB48 Mail を開き、画面上の丸いボタン → 「カスタム」→ 保存した名前 → 画面をタップすると、録った操作がそのまま再生されます。再生が終わったらまたタップ</li>
      </ol>

      <h3>Android: パソコンにつないで自動録画</h3>
      <p>
        パソコンと USB でつなげる場合は、「画面録画 → ゆっくりドラッグ → 2.5 秒待つ」を指定した時間だけ自動でくり返すスクリプトを用意しています。こちらは放置できます(最後のメールに着いたことは判別しないので、時間で止めます)。{' '}
        <a href="https://github.com/akbmail-rescue/akbmail-rescue.github.io/tree/main/tools/android-autoscroll" target="_blank" rel="noreferrer">
          Android 自動スクロール録画の手順
        </a>
      </p>

      <h3>結果の保存について</h3>
      <ul>
        <li>結果の画像はこのブラウザの中に自動で保存され、「処理履歴」から後で開けます。ただし保存できる量には限りがあります(特に iPhone の Safari)</li>
        <li>動画 1 本ごとに ZIP をダウンロードして安全な場所に置き、処理履歴から「削除」しておくことをおすすめします</li>
      </ul>

      <h3>対応環境</h3>
      <ul>
        <li>PC / スマートフォンの最新の Chrome / Edge / Safari</li>
        <li>iPhone の画面収録(HEVC)を Windows の Chrome で読み込む場合、パソコンによっては解析に時間がかかります(自動で互換モードに切り替わります)</li>
        <li>動画・画像・文字情報は端末の外に送信されません。初回表示後はオフラインでも動作します</li>
      </ul>
    </div>
  )
}
